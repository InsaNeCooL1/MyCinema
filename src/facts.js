const FACT_DISMISSED_KEY = 'mycinema.factDismissedDate';

function getTodayDateKey() {
  const d = new Date();
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
}

function getFactOfDay() {
  if (!CINEMA_FACTS.length) return null;
  const d = new Date();
  const dayIndex = Math.floor(Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()) / 86400000);
  const idx = ((dayIndex % CINEMA_FACTS.length) + CINEMA_FACTS.length) % CINEMA_FACTS.length;
  return CINEMA_FACTS[idx];
}

function isFactDismissedToday() {
  try {
    return localStorage.getItem(FACT_DISMISSED_KEY) === getTodayDateKey();
  } catch {
    return false;
  }
}

function dismissFactToday() {
  try {
    localStorage.setItem(FACT_DISMISSED_KEY, getTodayDateKey());
  } catch {}
}

async function openFactMedia(fact) {
  if (!fact || !fact.query) return;
  try {
    const type = fact.type === 'tv' ? 'tv' : 'movie';
    const yParam = fact.year ? (type === 'tv' ? `&first_air_date_year=${fact.year}` : `&year=${fact.year}`) : '';
    const data = await tmdbFetch(`/search/${type}?language=uk-UA&query=${encodeURIComponent(fact.query)}${yParam}`);
    let hit = (data.results || [])[0];
    if (!hit && yParam) {
      const fallback = await tmdbFetch(`/search/${type}?language=uk-UA&query=${encodeURIComponent(fact.query)}`);
      hit = (fallback.results || [])[0];
    }
    if (hit) {
      openCard(normalizeItem({ ...hit, media_type: type }));
    } else {
      showSyncToast('Тайтл не знайдено на TMDB');
    }
  } catch (e) {
    showSyncToast('Помилка відкриття картки');
  }
}
