function mcProj(lon, lat) {
  const x = ((lon + 180) * (1000 / 360)).toFixed(1);
  const y = ((90 - lat) * (500 / 180)).toFixed(1);
  return x + ',' + y;
}

function buildCountryPathD(polys) {
  return polys.map(poly => 'M' + poly.map(([lon, lat]) => mcProj(lon, lat)).join('L') + 'Z').join(' ');
}

function buildWorldMapWidget(countryStatsMap, onSelectCountry) {
  const wrap = el('div', 'world-map-card');
  const head = el('div', 'world-map-head');
  head.append(el('span', 'world-map-title', '🗺️ Мапа переглядів'));
  const tip = el('span', 'world-map-tip', 'Торкнися країни');
  head.append(tip);
  wrap.append(head);

  let maxCount = 1;
  for (const st of countryStatsMap.values()) {
    if (st.watched > maxCount) maxCount = st.watched;
  }

  const svgNS = 'http://www.w3.org/2000/svg';
  const svg = document.createElementNS(svgNS, 'svg');
  svg.setAttribute('viewBox', '0 40 1000 410');
  svg.setAttribute('class', 'world-map-svg');

  MC_WORLD_COUNTRIES.forEach(c => {
    const st = countryStatsMap.get(c.code);
    const p = document.createElementNS(svgNS, 'path');
    p.setAttribute('d', buildCountryPathD(c.polys));
    p.setAttribute('data-code', c.code);
    p.setAttribute('class', 'world-map-country' + (st ? ' visited' : ''));
    if (st) {
      const ratio = 0.32 + 0.68 * Math.sqrt(st.watched / maxCount);
      p.style.fillOpacity = ratio.toFixed(2);
    }
    p.addEventListener('click', () => {
      svg.querySelectorAll('.world-map-country.selected').forEach(n => n.classList.remove('selected'));
      p.classList.add('selected');
      const meta = typeof getCountryMeta === 'function' ? getCountryMeta(c.code) : { flag: '', name: c.name };
      if (st) {
        const avgStr = st.avg > 0 ? ` · ⭐ ${fmtNum(st.avg)}` : '';
        tip.textContent = `${meta.flag} ${meta.name}: ${st.watched}${avgStr}`;
        tip.classList.add('has-data');
        if (typeof onSelectCountry === 'function') onSelectCountry(c.code);
      } else {
        tip.textContent = `${meta.flag} ${meta.name} · ще не відкрито`;
        tip.classList.remove('has-data');
      }
    });
    svg.appendChild(p);
  });

  wrap.append(svg);
  return wrap;
}
