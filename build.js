// ⚠️ Порядок стилів критичний: це послідовні шматки старого styles.css.
// Не сортувати автоматично й не переставляти — каскад залежить від порядку.
const CSS_FILES = [
  'styles/00-foundation.css',
  'styles/01-home-intro.css',
  'styles/10-card.css',
  'styles/20-desktop-stats.css',
  'styles/30-effects-misc.css',
  'styles/40-nav.css',
  'styles/50-home-stats.css',
  'styles/60-perf-home.css',
  'styles/70-fixes-settings.css',
  'styles/75-collections.css',
  'styles/80-notes-card.css',
  'styles/85-chat.css',
  'styles/90-layout-safe.css',
  'styles/95-layout-a11y.css',
  'styles/97-modals.css',
  'styles/99-final.css',
];

let combined = '/* MyCinema bundle — auto-generated by build.js. Do not edit. */\n';
for (const f of SRC_FILES) {
  const code = fs.readFileSync(f, 'utf8');
  combined += `\n/* === ${f} === */\n${code}\n`;
}

const result = esbuild.transformSync(combined, {
  minifyWhitespace: true,
  minifySyntax: true,
  minifyIdentifiers: false, // ⚠️ КРИТИЧНО: інакше saveToCloud/loadHome перейменуються → inline-модуль Supabase зламається
  target: 'es2020',
  loader: 'js',
});

fs.writeFileSync('bundle.js', result.code);
const origSize = combined.length;
const minSize = result.code.length;
const pct = ((1 - minSize / origSize) * 100).toFixed(1);
console.log(`✅ bundle.js: ${origSize} B → ${minSize} B (${pct}% saved)`);

// styles.css — теж генерований файл. Редагувати треба styles/*.css.
let css = '/* MyCinema styles — auto-generated by build.js from styles/*.css. Do not edit. */\n';
for (const f of CSS_FILES) css += fs.readFileSync(f, 'utf8');
fs.writeFileSync('styles.css', css);
console.log(`✅ styles.css: ${CSS_FILES.length} modules → ${Buffer.byteLength(css)} B`);
