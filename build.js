// MyCinema bundle builder
// Запуск: npm run build
const fs = require('fs');
const esbuild = require('esbuild');

// ⚠️ Порядок ТОЧНО як у index.html — критично, бо скрипти залежать один від одного
const SRC_FILES = [
  'src/config.js',
  'src/core.js',
  'src/api.js',
  'src/ui.js',
  'src/facts.js',
  'src/search.js',
  'src/home.js',
  'src/library.js',
  'src/share.js',
  'src/stats.js',
  'src/game.js',
  'src/streams.js',
  'src/card/engine.js',
  'src/card/tabs.js',
  'src/card/mobile.js',
  'src/card/desktop.js',
  'src/person.js',
  'src/company.js',
  'src/settings.js',
  'src/calendar.js',
  'src/spatial-nav.js',
  'src/app.js',
  'src/snow.js',
];

let combined = '/* MyCinema bundle — auto-generated by build.js. Do not edit. */\n';
for (const f of SRC_FILES) {
  const code = fs.readFileSync(f, 'utf8');
  combined += `\n/* === ${f} === */\n${code}\n`;
}

const result = esbuild.transformSync(combined, {
  minifyWhitespace: true,
  minifySyntax: true,
  minifyIdentifiers: false, // ⚠️ КРИТИЧНО: інакше saveToCloud/loadHome перейменуються → inline-модуль Supabase зламається
  target: 'es2020',
  loader: 'js',
});

fs.writeFileSync('bundle.js', result.code);
const origSize = combined.length;
const minSize = result.code.length;
const pct = ((1 - minSize / origSize) * 100).toFixed(1);
console.log(`✅ bundle.js: ${origSize} B → ${minSize} B (${pct}% saved)`);
